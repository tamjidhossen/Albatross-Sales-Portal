// 1. OPENING STOCK SLIP
// -------------------------------------------------------------
export function downloadOpeningStockSlip({
  sessionDate,
  items,
  khuchra = 0,
  isLocked = false,
}: OpeningSlipData) {
  const width = 680;
  const rowHeight = 28;
  const tableRows = Math.max(1, items.length);
  const totalHeight = 110 + 90 + 35 + (tableRows * rowHeight) + 36 + 65 + 40;

  const { canvas, ctx } = setupCanvas(width, totalHeight);
  if (!ctx) return;

  drawHeaderBanner(
    ctx,
    width,
    'ALBATROSS FOOD CART',
    'Circuit House Field, Joypurhat • Morning Opening Stock Slip',
    sessionDate,
    isLocked
  );

  let y = 118;

  // 4 Metric Cards Across
  const totalLeftover = items.reduce((s, i) => s + i.morningCarriedOver, 0);
  const totalNew = items.reduce((s, i) => s + i.morningNewPrepared, 0);
  const totalAvail = items.reduce((s, i) => s + i.totalAvailable, 0);
  const totalStockVal = items.reduce((s, i) => s + (i.totalAvailable * i.unitPrice), 0);

  const cardSpacing = 6;
  const contentWidth = width - 48;
  const cardWidth = (contentWidth - (cardSpacing * 3)) / 4;
  const cardHeight = 64;

  const drawCard = (x: number, title: string, value: string, subtitle: string, valColor = '#0F172A') => {
    ctx.fillStyle = '#F8FAFC';
    ctx.strokeStyle = '#E2E8F0';
    ctx.lineWidth = 1;
    ctx.beginPath();
    ctx.roundRect(x, y, cardWidth, cardHeight, 8);
    ctx.fill();
    ctx.stroke();

    ctx.fillStyle = '#64748B';
    ctx.font = 'bold 9px system-ui, -apple-system, sans-serif';
    ctx.fillText(title, x + 8, y + 17);

    ctx.fillStyle = valColor;
    ctx.font = 'bold 14px system-ui, -apple-system, sans-serif';
    ctx.fillText(value, x + 8, y + 36);

    ctx.fillStyle = '#94A3B8';
    ctx.font = '9px system-ui, -apple-system, sans-serif';
    ctx.fillText(subtitle, x + 8, y + 51);
  };

  drawCard(24, 'TOTAL STOCK VALUE', `৳${totalStockVal.toLocaleString()}`, 'Food value loaded', '#EA4300');
  drawCard(24 + (cardWidth + cardSpacing), 'TOTAL AVAILABLE', `${totalAvail} pcs`, 'Ready to sell', '#0F172A');
  drawCard(24 + (cardWidth + cardSpacing) * 2, 'NEW MADE TODAY', `+${totalNew} pcs`, 'Prepared morning', '#059669');
  drawCard(24 + (cardWidth + cardSpacing) * 3, 'CARRIED OVER', `${totalLeftover} pcs`, 'Yesterday leftover', '#475569');

  y += cardHeight + 20;

  // Table Section Header
  ctx.fillStyle = '#EA4300';
  ctx.font = 'bold 12px system-ui, -apple-system, sans-serif';
  ctx.fillText('OPENING INVENTORY BREAKDOWN', 24, y);

  y += 10;

  // Table Header Bar
  ctx.fillStyle = '#F1F5F9';
  ctx.fillRect(24, y, contentWidth, 24);

  ctx.fillStyle = '#475569';
  ctx.font = 'bold 10px system-ui, -apple-system, sans-serif';
  ctx.fillText('FOOD ITEM', 36, y + 16);
  ctx.textAlign = 'center';
  ctx.fillText('LEFTOVER', 270, y + 16);
  ctx.fillText('NEW MADE', 350, y + 16);
  ctx.fillText('TOTAL AVAIL', 430, y + 16);
  ctx.fillText('UNIT PRICE', 510, y + 16);
  ctx.textAlign = 'right';
  ctx.fillText('STOCK VALUE (৳)', width - 36, y + 16);
  ctx.textAlign = 'left';

  y += 24;

  // Item rows
  items.forEach((item, index) => {
    ctx.fillStyle = index % 2 === 0 ? '#FFFFFF' : '#F8FAFC';
    ctx.fillRect(24, y, contentWidth, rowHeight);

    ctx.fillStyle = '#0F172A';
    ctx.font = '11px system-ui, -apple-system, sans-serif';
    ctx.fillText(item.productName.length > 30 ? item.productName.slice(0, 28) + '...' : item.productName, 36, y + 18);

    ctx.textAlign = 'center';
    ctx.fillStyle = item.morningCarriedOver > 0 ? '#475569' : '#94A3B8';
    ctx.fillText(`${item.morningCarriedOver}`, 270, y + 18);

    ctx.fillStyle = item.morningNewPrepared > 0 ? '#059669' : '#94A3B8';
    ctx.fillText(`+${item.morningNewPrepared}`, 350, y + 18);

    ctx.fillStyle = '#0F172A';
    ctx.font = 'bold 11px system-ui, -apple-system, sans-serif';
    ctx.fillText(`${item.totalAvailable}`, 430, y + 18);

    ctx.fillStyle = '#64748B';
    ctx.font = '11px system-ui, -apple-system, sans-serif';
    ctx.fillText(`৳${item.unitPrice}`, 510, y + 18);

    ctx.textAlign = 'right';
    ctx.fillStyle = '#EA4300';
    ctx.font = 'bold 11px system-ui, -apple-system, sans-serif';
    ctx.fillText(`৳${(item.totalAvailable * item.unitPrice).toLocaleString()}`, width - 36, y + 18);
    ctx.textAlign = 'left';

    y += rowHeight;
  });

  // Total Summary Row
  ctx.fillStyle = '#FFF7ED';
  ctx.strokeStyle = '#FDBA74';
  ctx.lineWidth = 1;
  ctx.fillRect(24, y, contentWidth, 28);
  ctx.strokeRect(24, y, contentWidth, 28);

  ctx.fillStyle = '#9A3412';
  ctx.font = 'bold 11px system-ui, -apple-system, sans-serif';
  ctx.fillText('= TOTAL', 36, y + 18);

  ctx.textAlign = 'center';
  ctx.fillText(`${totalLeftover}`, 270, y + 18);
  ctx.fillText(`+${totalNew}`, 350, y + 18);
  ctx.fillText(`${totalAvail} pcs`, 430, y + 18);
  ctx.fillText('—', 510, y + 18);

  ctx.textAlign = 'right';
  ctx.font = 'bold 12px system-ui, -apple-system, sans-serif';
  ctx.fillText(`৳${totalStockVal.toLocaleString()}`, width - 36, y + 18);
  ctx.textAlign = 'left';

  y += 38;

  // Morning Khuchra Drawer note box
  if (khuchra > 0) {
    ctx.fillStyle = '#F8FAFC';
    ctx.strokeStyle = '#E2E8F0';
    ctx.beginPath();
    ctx.roundRect(24, y, contentWidth, 32, 6);
    ctx.fill();
    ctx.stroke();

    ctx.fillStyle = '#475569';
    ctx.font = '11px system-ui, -apple-system, sans-serif';
    ctx.fillText('Morning Khuchra Cash taken from reserve for drawer:', 36, y + 20);

    ctx.textAlign = 'right';
    ctx.fillStyle = '#059669';
    ctx.font = 'bold 12px system-ui, -apple-system, sans-serif';
    ctx.fillText(`৳${khuchra.toLocaleString()}`, width - 36, y + 20);
    ctx.textAlign = 'left';

    y += 42;
  }

  y += 10;
  drawFooter(ctx, width, y);

  triggerDownload(canvas, `albatross-opening-stock-${sessionDate}.png`);
}

