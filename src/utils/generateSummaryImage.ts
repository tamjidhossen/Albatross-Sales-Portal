// Common canvas setup helper
function setupCanvas(width: number, totalHeight: number, scale = 2) {
  const canvas = document.createElement('canvas');
  canvas.width = width * scale;
  canvas.height = totalHeight * scale;
  const ctx = canvas.getContext('2d');
  if (ctx) {
    ctx.scale(scale, scale);
    ctx.fillStyle = '#FFFFFF';
    ctx.fillRect(0, 0, width, totalHeight);
  }
  return { canvas, ctx };
}

// Common top banner
function drawHeaderBanner(
  ctx: CanvasRenderingContext2D,
  width: number,
  title: string,
  subtitle: string,
  sessionDate: string,
  isLocked: boolean
) {
  // Orange Header
  ctx.fillStyle = '#EA4300';
  ctx.fillRect(0, 0, width, 100);

  // Brand Name
  ctx.fillStyle = '#FFFFFF';
  ctx.font = 'bold 22px system-ui, -apple-system, sans-serif';
  ctx.fillText('ALBATROSS FOOD CART', 24, 38);

  ctx.font = '12px system-ui, -apple-system, sans-serif';
  ctx.fillStyle = 'rgba(255, 255, 255, 0.9)';
  ctx.fillText(subtitle, 24, 58);

  // Date line
  ctx.font = 'bold 12px system-ui, -apple-system, sans-serif';
  ctx.fillStyle = '#FFDD00';
  ctx.fillText(`DATE: ${sessionDate}`, 24, 82);

  // Status Badge
  const statusText = isLocked ? 'STATUS: CLOSED & VERIFIED' : 'STATUS: SHIFT OPEN';
  ctx.fillStyle = isLocked ? '#D1FAE5' : '#FEF3C7';
  ctx.textAlign = 'right';
  ctx.fillText(statusText, width - 24, 82);
  ctx.textAlign = 'left';
}

// Common footer
function drawFooter(ctx: CanvasRenderingContext2D, width: number, y: number) {
  ctx.fillStyle = '#94A3B8';
  ctx.font = '10px system-ui, -apple-system, sans-serif';
  ctx.textAlign = 'center';
  ctx.fillText(`Generated by Albatross Food Cart Portal • ${new Date().toLocaleString()}`, width / 2, y);
  ctx.textAlign = 'left';
}

// Trigger browser download
function triggerDownload(canvas: HTMLCanvasElement, filename: string) {
  const link = document.createElement('a');
  link.download = filename;
  link.href = canvas.toDataURL('image/png');
  link.click();
}

