// 2. NIGHT CLOSING SLIP
// -------------------------------------------------------------
export function downloadClosingStockSlip({
  sessionDate,
  items,
  estimatedDiscounts = 0,
  isLocked = false,
}: ClosingSlipData) {
  const width = 680;
  const rowHeight = 28;
  const tableRows = Math.max(1, items.length);
  const totalHeight = 110 + 90 + 35 + (tableRows * rowHeight) + 36 + 70 + 40;

  const { canvas, ctx } = setupCanvas(width, totalHeight);
  if (!ctx) return;

  drawHeaderBanner(
    ctx,
    width,
    'ALBATROSS FOOD CART',
    'Circuit House Field, Joypurhat • Night Closing & Sales Slip',
    sessionDate,
    isLocked
  );

  let y = 118;

  const totalLoaded = items.reduce((s, i) => s + i.totalAvailable, 0);
  const totalSold = items.reduce((s, i) => s + i.quantitySold, 0);
  const totalUsable = items.reduce((s, i) => s + i.closingUsableLeftover, 0);
  const totalWaste = items.reduce((s, i) => s + i.closingWasted, 0);
  const grossSales = items.reduce((s, i) => s + i.estimatedRevenue, 0);
  const netSales = Math.max(0, grossSales - estimatedDiscounts);

  const cardSpacing = 6;
  const contentWidth = width - 48;
  const cardWidth = (contentWidth - (cardSpacing * 3)) / 4;
  const cardHeight = 64;

  const drawCard = (x: number, title: string, value: string, subtitle: string, valColor = '#0F172A') => {
    ctx.fillStyle = '#F8FAFC';
    ctx.strokeStyle = '#E2E8F0';
    ctx.lineWidth = 1;
    ctx.beginPath();
    ctx.roundRect(x, y, cardWidth, cardHeight, 8);
    ctx.fill();
    ctx.stroke();

    ctx.fillStyle = '#64748B';
    ctx.font = 'bold 9px system-ui, -apple-system, sans-serif';
    ctx.fillText(title, x + 8, y + 17);

    ctx.fillStyle = valColor;
    ctx.font = 'bold 14px system-ui, -apple-system, sans-serif';
    ctx.fillText(value, x + 8, y + 36);

    ctx.fillStyle = '#94A3B8';
    ctx.font = '9px system-ui, -apple-system, sans-serif';
    ctx.fillText(subtitle, x + 8, y + 51);
  };

  drawCard(24, 'NET FOOD SALES', isLocked ? `৳${netSales.toLocaleString()}` : '[Pending Lock]', isLocked ? `${totalSold} items sold` : 'Locks at closing', '#059669');
  drawCard(24 + (cardWidth + cardSpacing), 'ITEMS SOLD', `${totalSold} pcs`, `Of ${totalLoaded} loaded`, '#0F172A');
  drawCard(24 + (cardWidth + cardSpacing) * 2, 'LEFTOVER TOMORROW', `${totalUsable} pcs`, 'Usable stock', '#475569');
  drawCard(24 + (cardWidth + cardSpacing) * 3, 'ITEMS WASTED', `${totalWaste} pcs`, 'Spoiled/lost', totalWaste > 0 ? '#DC2626' : '#94A3B8');

  y += cardHeight + 20;

  // Table Section Header
  ctx.fillStyle = '#EA4300';
  ctx.font = 'bold 12px system-ui, -apple-system, sans-serif';
  ctx.fillText('CLOSING INVENTORY & SALES AUDIT', 24, y);

  y += 10;

  // Table Header Bar
  ctx.fillStyle = '#F1F5F9';
  ctx.fillRect(24, y, contentWidth, 24);

  ctx.fillStyle = '#475569';
  ctx.font = 'bold 10px system-ui, -apple-system, sans-serif';
  ctx.fillText('FOOD ITEM', 36, y + 16);
  ctx.textAlign = 'center';
  ctx.fillText('LOADED', 260, y + 16);
  ctx.fillText('SOLD', 330, y + 16);
  ctx.fillText('LEFTOVER', 400, y + 16);
  ctx.fillText('WASTE', 470, y + 16);
  ctx.fillText('PRICE', 530, y + 16);
  ctx.textAlign = 'right';
  ctx.fillText('SALES (৳)', width - 36, y + 16);
  ctx.textAlign = 'left';

  y += 24;

  // Item rows
  items.forEach((item, index) => {
    ctx.fillStyle = index % 2 === 0 ? '#FFFFFF' : '#F8FAFC';
    ctx.fillRect(24, y, contentWidth, rowHeight);

    ctx.fillStyle = '#0F172A';
    ctx.font = '11px system-ui, -apple-system, sans-serif';
    ctx.fillText(item.productName.length > 28 ? item.productName.slice(0, 26) + '...' : item.productName, 36, y + 18);

    ctx.textAlign = 'center';
    ctx.fillStyle = '#64748B';
    ctx.fillText(`${item.totalAvailable}`, 260, y + 18);

    ctx.fillStyle = '#0F172A';
    ctx.font = 'bold 11px system-ui, -apple-system, sans-serif';
    ctx.fillText(`${item.quantitySold}`, 330, y + 18);

    ctx.fillStyle = item.closingUsableLeftover > 0 ? '#0F172A' : '#94A3B8';
    ctx.font = '11px system-ui, -apple-system, sans-serif';
    ctx.fillText(`${item.closingUsableLeftover}`, 400, y + 18);

    ctx.fillStyle = item.closingWasted > 0 ? '#DC2626' : '#94A3B8';
    ctx.fillText(`${item.closingWasted}`, 470, y + 18);

    ctx.fillStyle = '#64748B';
    ctx.fillText(isLocked ? `৳${item.unitPrice}` : '—', 530, y + 18);

    ctx.textAlign = 'right';
    ctx.fillStyle = '#059669';
    ctx.font = 'bold 11px system-ui, -apple-system, sans-serif';
    ctx.fillText(isLocked ? `৳${item.estimatedRevenue.toLocaleString()}` : '[Pending]', width - 36, y + 18);
    ctx.textAlign = 'left';

    y += rowHeight;
  });

  // Total Summary Row
  ctx.fillStyle = '#ECFDF5';
  ctx.strokeStyle = '#6EE7B7';
  ctx.lineWidth = 1;
  ctx.fillRect(24, y, contentWidth, 28);
  ctx.strokeRect(24, y, contentWidth, 28);

  ctx.fillStyle = '#065F46';
  ctx.font = 'bold 11px system-ui, -apple-system, sans-serif';
  ctx.fillText('= TOTAL', 36, y + 18);

  ctx.textAlign = 'center';
  ctx.fillText(`${totalLoaded}`, 260, y + 18);
  ctx.fillText(`${totalSold}`, 330, y + 18);
  ctx.fillText(`${totalUsable}`, 400, y + 18);
  ctx.fillText(`${totalWaste}`, 470, y + 18);
  ctx.fillText('—', 530, y + 18);

  ctx.textAlign = 'right';
  ctx.font = 'bold 12px system-ui, -apple-system, sans-serif';
  ctx.fillText(isLocked ? `৳${grossSales.toLocaleString()}` : '[Pending Lock]', width - 36, y + 18);
  ctx.textAlign = 'left';

  y += 38;

  // Discounts & Net Sales Box
  ctx.fillStyle = '#F8FAFC';
  ctx.strokeStyle = '#E2E8F0';
  ctx.beginPath();
  ctx.roundRect(24, y, contentWidth, 38, 6);
  ctx.fill();
  ctx.stroke();

  ctx.fillStyle = '#475569';
  ctx.font = '11px system-ui, -apple-system, sans-serif';
  ctx.fillText(isLocked ? `Gross Sales: ৳${grossSales.toLocaleString()}` : 'Gross Sales: [Pending Lock]', 36, y + 23);
  if (estimatedDiscounts > 0 && isLocked) {
    ctx.fillStyle = '#D97706';
    ctx.fillText(`Discounts Given: −৳${estimatedDiscounts.toLocaleString()}`, 250, y + 23);
  }

  ctx.textAlign = 'right';
  ctx.fillStyle = '#059669';
  ctx.font = 'bold 13px system-ui, -apple-system, sans-serif';
  ctx.fillText(isLocked ? `Net Food Sales: ৳${netSales.toLocaleString()}` : 'Net Food Sales: [Pending Lock]', width - 36, y + 23);
  ctx.textAlign = 'left';

  y += 50;
  drawFooter(ctx, width, y);

  triggerDownload(canvas, `albatross-closing-slip-${sessionDate}.png`);
}

