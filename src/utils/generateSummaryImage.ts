// 4. CASH & PAYOUTS SETTLEMENT SLIP
// -------------------------------------------------------------
export function downloadCashSettlementSlip({
  session,
  items,
  expenses,
  payouts,
}: CashSlipData) {
  const width = 680;
  const payoutRows = payouts.length;
  const payoutSectionHeight = payoutRows > 0 ? 40 + (payoutRows * 24) + 10 : 0;
  const totalHeight = 110 + 290 + payoutSectionHeight + 90 + 50;

  const { canvas, ctx } = setupCanvas(width, totalHeight);
  if (!ctx) return;

  drawHeaderBanner(
    ctx,
    width,
    'ALBATROSS FOOD CART',
    'Circuit House Field, Joypurhat • Daily Cash & Drawer Settlement Slip',
    session.sessionDate,
    session.isLocked
  );

  let y = 120;
  const contentWidth = width - 48;
  const khuchra = session.khuchraTakenFromReserve || session.openingCash || 0;

  // CASH RECONCILIATION CARD
  ctx.fillStyle = '#F8FAFC';
  ctx.strokeStyle = '#E2E8F0';
  ctx.lineWidth = 1;
  ctx.beginPath();
  ctx.roundRect(24, y, contentWidth, 275, 10);
  ctx.fill();
  ctx.stroke();

  // Cash Section Header
  ctx.fillStyle = '#EA4300';
  ctx.font = 'bold 13px system-ui, -apple-system, sans-serif';
  ctx.fillText('CASH & SETTLEMENT RECONCILIATION', 38, y + 26);

  const drawRow = (label: string, value: string, rowY: number, color = '#1E293B', isBold = false) => {
    ctx.fillStyle = color;
    ctx.font = `${isBold ? 'bold' : 'normal'} 12px system-ui, -apple-system, sans-serif`;
    ctx.fillText(label, 38, rowY);
    ctx.textAlign = 'right';
    ctx.fillText(value, width - 38, rowY);
    ctx.textAlign = 'left';
  };

  drawRow('Khuchra Cash (Taken for Cart Opening):', `+৳${khuchra.toLocaleString()}`, y + 54, '#64748B');
  drawRow('Net Food Sales Revenue:', session.isLocked ? `+৳${session.netEstimatedRevenue.toLocaleString()}` : '[Pending Lock]', y + 78, '#059669', true);
  drawRow('Bazaar Expenses Paid from Drawer:', `−৳${session.totalExpenses.toLocaleString()}`, y + 102, '#DC2626');
  drawRow('Staff / Owner Payouts Taken from Drawer:', `−৳${session.totalPayouts.toLocaleString()}`, y + 126, '#DC2626');

  // Divider
  ctx.strokeStyle = '#CBD5E1';
  ctx.beginPath();
  ctx.moveTo(38, y + 142);
  ctx.lineTo(width - 38, y + 142);
  ctx.stroke();

  const expectedCash = khuchra + session.netEstimatedRevenue - session.totalExpenses - session.totalPayouts;
  drawRow('Expected Closing Drawer Cash:', `৳${expectedCash.toLocaleString()}`, y + 164, '#0F172A', true);

  const diff = session.actualCashCounted - expectedCash;
  const diffLabel = diff === 0 ? 'Exact Match (৳0)' : diff < 0 ? `Shortage: −৳${Math.abs(diff)}` : `Surplus: +৳${diff}`;
  const diffColor = diff === 0 ? '#059669' : diff < 0 ? '#DC2626' : '#D97706';
  drawRow('Actual Counted Drawer Cash Tonight:', `৳${session.actualCashCounted.toLocaleString()} (${diffLabel})`, y + 188, diffColor, true);

  // Reserve breakdown
  const isDrawerSaved = (session.transferredToReserve || 0) > 0;
  const safeCash = Math.max(0, session.openingSavedCash - khuchra);
  const totalReserve = isDrawerSaved ? session.closingSavedCash : (safeCash + khuchra);

  ctx.strokeStyle = '#CBD5E1';
  ctx.beginPath();
  ctx.moveTo(38, y + 206);
  ctx.lineTo(width - 38, y + 206);
  ctx.stroke();

  drawRow('Safe Cash in Reserve (Remaining):', `৳${safeCash.toLocaleString()}`, y + 226, '#64748B');
  drawRow('Drawer Cash Saved to Reserve:', isDrawerSaved ? `+৳${session.actualCashCounted.toLocaleString()}` : 'Pending settlement', y + 246, isDrawerSaved ? '#059669' : '#94A3B8');
  drawRow('Total Business Cash Reserve Now:', `৳${totalReserve.toLocaleString()}`, y + 266, '#EA4300', true);

  y += 295;

  // PAYOUTS BREAKDOWN TABLE (if any payouts exist)
  if (payouts.length > 0) {
    ctx.fillStyle = '#EA4300';
    ctx.font = 'bold 12px system-ui, -apple-system, sans-serif';
    ctx.fillText('STAFF & OWNER PAYOUTS RECORD', 24, y);

    y += 10;

    ctx.fillStyle = '#F1F5F9';
    ctx.fillRect(24, y, contentWidth, 22);

    ctx.fillStyle = '#475569';
    ctx.font = 'bold 10px system-ui, -apple-system, sans-serif';
    ctx.fillText('TIME', 36, y + 15);
    ctx.fillText('RECIPIENT', 140, y + 15);
    ctx.fillText('PAYOUT PURPOSE', 330, y + 15);
    ctx.textAlign = 'right';
    ctx.fillText('AMOUNT (৳)', width - 36, y + 15);
    ctx.textAlign = 'left';

    y += 22;

    payouts.forEach((p, idx) => {
      ctx.fillStyle = idx % 2 === 0 ? '#FFFFFF' : '#F8FAFC';
      ctx.fillRect(24, y, contentWidth, 24);

      ctx.fillStyle = '#64748B';
      ctx.font = '11px system-ui, -apple-system, sans-serif';
      ctx.fillText(p.createdAt || '—', 36, y + 16);

      ctx.fillStyle = '#0F172A';
      ctx.font = 'bold 11px system-ui, -apple-system, sans-serif';
      ctx.fillText(p.recipientName, 140, y + 16);

      ctx.fillStyle = '#475569';
      ctx.fillText(p.payoutType, 330, y + 16);

      ctx.textAlign = 'right';
      ctx.fillStyle = '#DC2626';
      ctx.font = 'bold 11px system-ui, -apple-system, sans-serif';
      ctx.fillText(`৳${p.amount.toLocaleString()}`, width - 36, y + 16);
      ctx.textAlign = 'left';

      y += 24;
    });

    y += 15;
  }

  // End Summary Bar
  ctx.fillStyle = '#F8FAFC';
  ctx.strokeStyle = '#E2E8F0';
  ctx.beginPath();
  ctx.roundRect(24, y, contentWidth, 42, 8);
  ctx.fill();
  ctx.stroke();

  ctx.fillStyle = '#334155';
  ctx.font = '11px system-ui, -apple-system, sans-serif';
  ctx.fillText(`Food Sales: ৳${session.grossEstimatedRevenue.toLocaleString()} (${session.totalProductsSold} sold)`, 38, y + 25);

  ctx.textAlign = 'right';
  ctx.fillStyle = '#EA4300';
  ctx.font = 'bold 12px system-ui, -apple-system, sans-serif';
  ctx.fillText(`Total Cash Reserve: ৳${totalReserve.toLocaleString()}`, width - 38, y + 25);
  ctx.textAlign = 'left';

  y += 55;
  drawFooter(ctx, width, y);

  triggerDownload(canvas, `albatross-cash-slip-${session.sessionDate}.png`);
}

